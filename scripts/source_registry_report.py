"""Write docs/official_sources.md from the source catalog and a live probe.

    python -m legal_core.cli probe-sources > probe.json
    python scripts/source_registry_report.py probe.json --date 2026-10-22

The table is generated so the documented status of every official source is the measured one.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from legal_core.source_catalog import CATEGORIES, SOURCES, integration_status

CONNECTOR = {
    "rss": "Official RSS feed",
    "html_listing": "Document listing",
    "moj_judgments_api": "Public judgments API",
    "page_watch": "Change detection only",
    "none": "Not harvested",
}
HEALTH = {
    "available": "Available",
    "degraded": "Readable, no extractable items",
    "unavailable": "Unavailable",
    "blocked": "Blocked for automated clients",
    "robots_disallowed": "Disallowed by robots.txt",
    "consolidated": "See target entry",
}


def build(probe: list[dict], probed_on: str) -> str:
    by_name = {row["source"]: row for row in probe}
    lines = [
        "# Official source registry",
        "",
        "<!-- Generated by scripts/source_registry_report.py; edit legal_core/source_catalog.py instead. -->",
        "",
        "Every entry of the approved list is registered in `source_registry` (`python -m legal_core.cli seed-sources`).",
        "Reachability below was measured on " + probed_on + " by `python -m legal_core.cli probe-sources`, which",
        "reads each endpoint once with its connector, honours robots.txt, and records the result on the source row.",
        "The operations screen **المصادر الرسمية** shows the same data live; every nightly run refreshes it.",
        "",
        "Integration terms:",
        "",
        "* **integrated**: the connector discovers documents (or judgments) and fetches their official text, which",
        "  then goes through parsing and the deterministic release gate. Discovery never publishes on its own.",
        "* **discovery_only**: the page renders its list with JavaScript, blocks automated clients, or is a",
        "  news or directory page. Only a change of its visible text is detected and logged; nothing is published.",
        "* **not_integrated**: no permitted automated access path. The endpoint is probed for reachability only.",
        "* **consolidated**: same endpoint or content as another entry, which reads it.",
        "",
    ]
    for category, title in CATEGORIES.items():
        lines += [f"## {category}. {title}", "", "| # | Source | Endpoint read | Connector | Integration | Status (" + probed_on + ") | Notes |", "|---|---|---|---|---|---|---|"]
        for source in SOURCES:
            if source.category != category:
                continue
            row = by_name.get(source.name, {})
            status = row.get("status", "not probed")
            detail = row.get("detail") or ""
            if row.get("http_status"):
                detail = f"HTTP {row['http_status']}. {detail}".strip()
            notes = source.access_notes.replace("|", "/")
            lines.append(
                f"| {', '.join(map(str, source.numbers))} | {source.name_ar}<br>{source.name} | `{source.endpoint}` | "
                f"{CONNECTOR[source.connector]} | {integration_status(source)} | {HEALTH.get(status, status)}"
                f"{': ' + detail if detail and status != 'consolidated' else ''} | {notes} |"
            )
        lines.append("")
    integrated = [s for s in SOURCES if integration_status(s) == "integrated"]
    problems = [r for r in probe if r.get("status") in ("unavailable", "blocked", "robots_disallowed")]
    lines += [
        "## Summary",
        "",
        f"* Registered entries: {sum(len(s.numbers) for s in SOURCES)} (in {len(SOURCES)} registry rows).",
        f"* Integrated connectors: {len(integrated)}; change detection only: "
        f"{sum(integration_status(s) == 'discovery_only' for s in SOURCES)}; not harvested: "
        f"{sum(integration_status(s) == 'not_integrated' for s in SOURCES)}; consolidated: "
        f"{sum(integration_status(s) == 'consolidated' for s in SOURCES)}.",
        f"* Not reachable or refused on {probed_on}: "
        + (", ".join(f"{r['source']} ({HEALTH.get(r['status'], r['status'])})" for r in problems) or "none")
        + ".",
        "",
        "Unavailable sources are retried by every nightly run. A failed source never removes a published legal",
        "version and is never reported as synchronized.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("probe")
    parser.add_argument("--date", required=True)
    parser.add_argument("--out", default="docs/official_sources.md")
    args = parser.parse_args()
    probe = json.loads(Path(args.probe).read_text(encoding="utf-8"))
    Path(args.out).write_text(build(probe, args.date), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
